func skillSnapshotFixture(t *testing.T) (*app, skillPackage, SkillSnapshot) {
	t.Helper()
	root := t.TempDir()
	t.Setenv("KLM_USER_SKILLS_DIR", root)
	writeSkillFixtureFile(t, filepath.Join(root, "fixture-skill", "SKILL.md"), "---\nname: fixture-skill\ndescription: Snapshot regression fixture\n---\n")
	writeSkillFixtureFile(t, filepath.Join(root, "fixture-skill", "scripts", "core.py"), "VALUE = 1\n")
	pkg, err := stableSkillPackage(root, "fixture-skill", false)
	if err != nil {
		t.Fatal(err)
	}
	a := &app{dir: t.TempDir()}
	snapshot, err := a.materializeSkill(pkg, false)
	if err != nil {
		t.Fatal(err)
	}
	return a, pkg, snapshot
}

func writeSkillFixtureFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestSkillSnapshotBytecodeRecoveryAllHarnesses(t *testing.T) {
	for _, harness := range []string{"pi", "opencode", "codex"} {
		t.Run(harness, func(t *testing.T) {
			a, pkg, snapshot := skillSnapshotFixture(t)
			selection := CapabilitySelection{Skills: []string{snapshot.ID}}
			first, err := a.captureCapabilities(context.Background(), selection, harness)
			if err != nil {
				t.Fatal(err)
			}
			cache := filepath.Join(a.skillSnapshotPath(snapshot), "scripts", "__pycache__", "core.cpython-313.pyc")
			writeSkillFixtureFile(t, cache, "generated bytecode")
			second, err := a.captureCapabilities(context.Background(), selection, harness)
			if err != nil {
				t.Fatal(err)
			}
			if first.Revision != second.Revision {
				t.Fatal("recovery changed the captured capability revision")
			}
			if _, err := os.Stat(cache); !os.IsNotExist(err) {
				t.Fatal("executable cache was ignored instead of removed")
			}
			// Frozen graph/automation snapshots must recover without reloading or
			// requiring the current user-library source.
			writeSkillFixtureFile(t, cache, "generated again")
			if err := os.RemoveAll(os.Getenv("KLM_USER_SKILLS_DIR")); err != nil {
				t.Fatal(err)
			}
			captured, err := a.readSkillSnapshot(snapshot)
			if err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(captured.Files, pkg.Files) {
				t.Fatal("recovery did not retain the original captured bytes")
			}
		})
	}
}

func TestSkillSnapshotBytecodeRecoveryPreservesIntegrity(t *testing.T) {
	for _, change := range []string{"modified-source", "missing-source", "extra-file", "extra-cache-file", "captured-bytecode"} {
		t.Run(change, func(t *testing.T) {
			a, pkg, snapshot := skillSnapshotFixture(t)
			if change == "captured-bytecode" {
				root := os.Getenv("KLM_USER_SKILLS_DIR")
				writeSkillFixtureFile(t, filepath.Join(root, snapshot.ID, "scripts", "core.pyc"), "original captured bytecode")
				var err error
				pkg, err = stableSkillPackage(root, snapshot.ID, false)
				if err != nil {
					t.Fatal(err)
				}
				snapshot, err = a.materializeSkill(pkg, false)
				if err != nil {
					t.Fatal(err)
				}
			}
			path := a.skillSnapshotPath(snapshot)
			cache := filepath.Join(path, "scripts", "__pycache__", "core.cpython-313.pyc")
			writeSkillFixtureFile(t, cache, "generated bytecode")
			switch change {
			case "modified-source":
				writeSkillFixtureFile(t, filepath.Join(path, "scripts", "core.py"), "VALUE = 2\n")
			case "missing-source":
				if err := os.Remove(filepath.Join(path, "scripts", "core.py")); err != nil {
					t.Fatal(err)
				}
			case "extra-file":
				writeSkillFixtureFile(t, filepath.Join(path, "scripts", "extra.py"), "extra")
			case "extra-cache-file":
				writeSkillFixtureFile(t, filepath.Join(path, "scripts", "__pycache__", "extra.txt"), "extra")
			}
			if _, err := a.readSkillSnapshot(snapshot); err == nil || !strings.Contains(err.Error(), "corrupted") {
				t.Fatalf("expected integrity failure, got %v", err)
			}
			if _, err := os.Stat(cache); err != nil {
				t.Fatal("failed recovery modified snapshot files")
			}
		})
	}
}

func TestSkillExecutionEnv(t *testing.T) {
	input := []string{"PATH=fixture", "PYTHONDONTWRITEBYTECODE=", "pythondontwritebytecode=0", "OTHER=unchanged"}
	want := []string{"PATH=fixture", "OTHER=unchanged", "PYTHONDONTWRITEBYTECODE=1"}
	if got := skillExecutionEnv(input); !reflect.DeepEqual(got, want) {
		t.Fatalf("unexpected environment: %v", got)
	}
	if input[1] != "PYTHONDONTWRITEBYTECODE=" {
		t.Fatal("mutated input environment")
	}
}
